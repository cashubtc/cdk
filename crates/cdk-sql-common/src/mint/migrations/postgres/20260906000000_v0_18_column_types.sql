-- The only amount columns the server computes rather than binds. Every other
-- one arrives as a u64 that cannot be out of range by construction, so this is
-- the one place a running total needs a bound. The type change already rewrites
-- the table, so validating the constraint costs nothing extra.
ALTER TABLE keyset_amounts
    ALTER COLUMN total_issued TYPE NUMERIC(20, 0),
    ALTER COLUMN total_redeemed TYPE NUMERIC(20, 0),
    ALTER COLUMN fee_collected TYPE NUMERIC(20, 0);

ALTER TABLE keyset_amounts
    ADD CONSTRAINT keyset_amounts_u64_range
    CHECK (total_issued   BETWEEN 0 AND 18446744073709551615
       AND total_redeemed BETWEEN 0 AND 18446744073709551615
       AND fee_collected  BETWEEN 0 AND 18446744073709551615);

